// threat-wall-api/lib/firewallGenerator.js
// Multi-Platform Firewall & WAF Rule Synthesizer

const { isValidIp } = require('./threatEngine');

/**
 * Generates drop/block rules for a given array of IP addresses across 8 platforms
 */
function generateFirewallRules(ips, options = {}) {
  const ipList = Array.isArray(ips) ? ips : [ips];
  const validIps = ipList.filter(ip => isValidIp(ip.trim()));

  if (validIps.length === 0) {
    return {
      success: false,
      error: 'No valid IPv4 or IPv6 addresses provided for firewall rule generation.'
    };
  }

  const comment = options.comment || 'ThreatWall Automated Blocklist';
  const action = options.action || 'DROP'; // DROP, REJECT, BLOCK

  // 1. Linux iptables
  const iptablesRules = validIps.map(ip => 
    `iptables -A INPUT -s ${ip} -m comment --comment "${comment}" -j ${action}`
  ).join('\n');

  // 2. Linux nftables
  const nftablesRule = [
    `# nftables atomic blackhole rule`,
    `table inet filter {`,
    `    set threatwall_blackhole {`,
    `        type ipv4_addr`,
    `        elements = { ${validIps.join(', ')} }`,
    `    }`,
    `    chain input {`,
    `        type filter hook input priority 0; policy accept;`,
    `        ip saddr @threatwall_blackhole drop`,
    `    }`,
    `}`
  ].join('\n');

  // 3. Nginx deny snippet
  const nginxRules = [
    `# ${comment}`,
    ...validIps.map(ip => `deny ${ip};`),
    `# Place above in your http {}, server {}, or location / {} block`
  ].join('\n');

  // 4. Cloudflare WAF Expression Builder format
  const cloudflareExpr = validIps.length === 1
    ? `(ip.src eq ${validIps[0]})`
    : `(ip.src in {${validIps.join(' ')}})`;

  const cloudflareApiPayload = {
    mode: 'block',
    configuration: {
      target: validIps.length === 1 ? 'ip' : 'ip_range',
      value: validIps[0]
    },
    notes: comment
  };

  // 5. AWS WAF v2 IPSet JSON (Terraform / CloudFormation / AWS CLI ready)
  const awsWafIpSet = {
    Name: 'ThreatWallBlockSet',
    Scope: 'REGIONAL',
    IPAddressVersion: 'IPV4',
    Description: `${comment} - Generated by ThreatWall API`,
    Addresses: validIps.map(ip => ip.includes('/') ? ip : `${ip}/32`)
  };

  // 6. Caddyfile snippet
  const caddyRule = [
    `# Caddy Web Server Blocklist`,
    `@threatwall_blocked remote_ip ${validIps.join(' ')}`,
    `abort @threatwall_blocked`
  ].join('\n');

  // 7. Traefik Middleware (YAML format)
  const traefikYaml = [
    `apiVersion: traefik.io/v1alpha1`,
    `kind: Middleware`,
    `metadata:`,
    `  name: threatwall-ip-blocklist`,
    `spec:`,
    `  ipAllowList:`,
    `    rejectStatusCode: 403`,
    `    sourceRange:`,
    `      # Blacklist inversion approach or use plugin-block-ip`,
    `      - "0.0.0.0/0"`,
    `      # Excluded: ${validIps.join(', ')}`
  ].join('\n');

  // 8. Apache .htaccess / VirtualHost
  const apacheRule = [
    `<RequireAll>`,
    `    Require all granted`,
    ...validIps.map(ip => `    Require not ip ${ip}`),
    `</RequireAll>`
  ].join('\n');

  // 9. Windows Defender Firewall (netsh command)
  const windowsFirewall = validIps.map(ip => 
    `netsh advfirewall firewall add rule name="ThreatWall_${ip}" dir=in action=block remoteip=${ip} description="${comment}"`
  ).join('\n');

  return {
    success: true,
    ip_count: validIps.length,
    ips: validIps,
    rules: {
      iptables: iptablesRules,
      nftables: nftablesRule,
      nginx: nginxRules,
      cloudflare_waf: {
        expression: cloudflareExpr,
        action: 'BLOCK',
        api_payload: cloudflareApiPayload
      },
      aws_waf_v2: awsWafIpSet,
      caddy: caddyRule,
      apache: apacheRule,
      traefik_middleware_yaml: traefikYaml,
      windows_firewall: windowsFirewall
    }
  };
}

module.exports = {
  generateFirewallRules
};
